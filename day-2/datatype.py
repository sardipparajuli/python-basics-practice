# 1. Integer (int) --> Used to store whole numbers (no decimals).
my_age = 21
print(my_age, type(my_age))

# 2. Float --> Used to store numbers with decimal points.
my_price = 99.99
print(my_price, type(my_price))

# 3. String (str) --> Used to store text, words, or characters (always inside quotes).
my_name = "Sardip"
print(my_name, type(my_name))

# 4. Boolean (bool) --> Used to store only two possible values: True or False.
is_student = True
print(is_student, type(is_student))

# 5. List --> Used to store multiple items in a single variable (changeable, inside square brackets).
my_fruits = ["apple", "banana", "mango"]
print(my_fruits, type(my_fruits))

# 6. Dictionary (dict) --> Used to store data in key:value pairs (like a real dictionary).
my_info = {"name": "Sardip", "course": "BSc CSIT"}
print(my_info, type(my_info))

# 7. Tuple --> Like a list, but CANNOT be changed (immutable).
my_location = (27.7172, 85.3240)
print(my_location, type(my_location))

# 8. Set --> A collection with NO duplicates.
my_unique_fruits = {"apple", "banana", "apple", "orange"}
print(my_unique_fruits, type(my_unique_fruits))

# 9. NoneType --> Used to represent the absence of a value (like an empty slot).
my_future_job = None
print(my_future_job, type(my_future_job)) 