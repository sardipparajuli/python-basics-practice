# DAY 1: Python Introduction & Setup


# 1. What is Python?
# Python is a high-level, interpreted programming language. 
# "High-level" means it's easy for humans to read and write.

# 2. Compiled vs Interpreted Language
# Compiled (like C++ or Java): Translates ALL the code into machine language at once before running it. If there is an error, it won't run at all.
# Interpreted (like Python): Translates and runs the code line-by-line. It stops exactly where it finds an error.

# 3. The Print Function
# The print() function is used to output text or numbers to the screen.
print("Hello, World!")
print("My name is Sardip.")
print("I am learning Python for Fullstack Development.")

# 4. Basic Math
# Python can be used as a calculator.
print(2 + 2)       # Addition
print(10 - 4)      # Subtraction
print(5 * 3)       # Multiplication
print(10 / 2)      # Division (always results in a float/decimal)

