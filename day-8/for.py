# For Loop:
# loop depends on the number of data existing in the iterable

# iterable: sequential data(group datatype, string)
# iteration: process of moving from 1st index to last index of the sequence
# iterator: variable used to perform interation in iterable

# syntax
# for iterator in iterable:
#     statement1
#     statement2
#     statement3

a = [1, 2, 3, 4, 5]
for i in a:            # i = 1, 2, 3, 4, 5
    print("Hello", i)